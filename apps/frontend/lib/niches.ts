export const formatNicheLabel = (niche: string): string => {
  if (!niche || niche === 'todos') return 'Todos';

  return niche
    .replace(/_/g, ' ')
    .replace(/-/g, ' ')
    .split(' ')
    .map((word) => SPECIAL_WORDS[word] || word.charAt(0).toUpperCase() + word.slice(1))
    .join(' ');
};